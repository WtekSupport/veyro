use crate::app::state::AppState;
use crate::settings::UiLocale;

pub fn translate(locale: UiLocale, key: &str, args: &[(&str, &str)]) -> String {
    let template = match locale {
        UiLocale::En => en(key),
        UiLocale::Ru => ru(key),
    };

    interpolate(template, args)
}

fn interpolate(template: &str, args: &[(&str, &str)]) -> String {
    let mut result = template.to_string();
    for (name, value) in args {
        result = result.replace(&format!("{{{name}}}"), value);
    }
    result
}

pub fn state_label(locale: UiLocale, state: AppState) -> String {
    let key = match state {
        AppState::Initializing => "states.initializing",
        AppState::Disabled => "states.disabled",
        AppState::Ready => "states.ready",
        AppState::Listening => "states.listening",
        AppState::Processing => "states.processing",
        AppState::Transcribing => "states.transcribing",
        AppState::Injecting => "states.injecting",
        AppState::Error => "states.error",
        AppState::PermissionRequired => "states.permission_required",
        AppState::MicrophoneUnavailable => "states.microphone_unavailable",
        AppState::NetworkUnavailable => "states.network_unavailable",
    };
    translate(locale, key, &[])
}

